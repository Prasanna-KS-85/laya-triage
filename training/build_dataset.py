"""Build NLBSE'24 splits, Laya rows and manifests (PROJECT_SPEC.md §8.3-§8.7).

Usage: .venv/bin/python training/build_dataset.py
Reads data/raw/issues_{train,test}.csv (sha256-verified first) and results/phase0_sample_ids.txt.
Writes data/processed/{train,val,test}.jsonl, data/processed/review_sample_30.md (issue text,
gitignored), data/manifests/{train,val,test,dropped_train}.txt, and the generated block of
data/DATA_CARD.md. Every §8.7 check is asserted before anything is written.

Rules:
- Drop every official-train row whose content hash also occurs in official test or more than
  once in official train (all copies), with the reasons in dropped_train.txt.
- val: per repo x label cell of the kept rows, round_half_up(20% of the cell) rows, drawn with one
  random.Random(42) over the cells in sorted order, from the cell's sorted row indices that are not
  Phase 0 sample rows. A cell that cannot supply its count is an error.
- train = kept rows not in val; test = all official test rows. Files list rows in raw-CSV order.
"""

import argparse
import json
import random
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

from nlbse_data import SHA256, SOURCES, content_hash, load_raw, make_id, sha256_file

from laya_triage import preprocess as pp
from laya_triage.questions import ISSUE_TYPE_QUESTION, LABELS

ROOT = Path(__file__).resolve().parents[1]
SEED = 42
VAL_PERCENT = 20
REVIEW_N = 30
REVIEW_BODY_CHARS = 600
QUESTION_ID = "issue_type"
REAL_TRAIN_ROWS = 1500
REAL_TEST_ROWS = 1500
REAL_DROPPED_ROWS = {559, 900, 901, 1114}
CARD_BEGIN = "<!-- BEGIN generated by training/build_dataset.py; do not edit by hand -->"
CARD_END = "<!-- END generated -->"
SPLITS = ("train", "val", "test")


class BuildError(Exception):
    pass


@dataclass(frozen=True)
class Record:
    source: str
    row: int
    id: str
    hash: str
    repo: str
    label: str
    title: str
    body: str


def to_records(source, rows):
    return [Record(source, i, make_id(source, i), content_hash(r["title"], r["body"]),
                   r["repo"], r["label"], r["title"], r["body"]) for i, r in enumerate(rows)]


def val_count(cell_size):
    return (cell_size * VAL_PERCENT + 50) // 100  # round half up


def make_splits(train, test, sample_rows):
    """Pure split logic. Returns {"train", "val", "test": [Record], "dropped": [(Record, reason)]}."""
    test_hashes = {r.hash for r in test}
    train_counts = Counter(r.hash for r in train)
    kept, dropped = [], []
    for r in train:
        reasons = []
        if r.hash in test_hashes:
            reasons.append("content also in official test")
        if train_counts[r.hash] > 1:
            reasons.append("content duplicated within official train")
        if reasons:
            dropped.append((r, "; ".join(reasons)))
        else:
            kept.append(r)
    lost = sorted(sample_rows & {r.row for r, _ in dropped})
    if lost:
        raise BuildError(f"Phase 0 sample rows would be dropped: {lost}")
    cells = defaultdict(list)
    for r in kept:
        cells[(r.repo, r.label)].append(r.row)
    rng = random.Random(SEED)
    val_rows = set()
    for cell in sorted(cells):
        k = val_count(len(cells[cell]))
        candidates = sorted(row for row in cells[cell] if row not in sample_rows)
        if len(candidates) < k:
            raise BuildError(f"cell {cell}: needs {k} val rows but only {len(candidates)} "
                             f"of {len(cells[cell])} rows are not Phase 0 sample rows")
        val_rows.update(rng.sample(candidates, k))
    return {
        "train": [r for r in kept if r.row not in val_rows],
        "val": [r for r in kept if r.row in val_rows],
        "test": list(test),
        "dropped": dropped,
    }


def check_splits(splits, n_train_raw, sample_rows):
    """§8.7 automated checks. Raises BuildError on the first failure."""
    seen_id, seen_hash = {}, {}
    for name in SPLITS:
        for r in splits[name]:
            if r.id in seen_id:
                raise BuildError(f"id {r.id} in both {seen_id[r.id]} and {name}")
            seen_id[r.id] = name
        for h in {r.hash for r in splits[name]}:
            if h in seen_hash:
                raise BuildError(f"content hash {h} in both {seen_hash[h]} and {name}")
            seen_hash[h] = name
    total = len(splits["train"]) + len(splits["val"]) + len(splits["dropped"])
    if total != n_train_raw:
        raise BuildError(f"train + val + dropped = {total}, expected {n_train_raw}")
    missing = sorted(sample_rows - {r.row for r in splits["train"]})
    if missing:
        raise BuildError(f"Phase 0 sample rows not in train: {missing}")


def train_row(r):
    state = pp.preprocess(r.title, r.body)
    gold = {QUESTION_ID: {"probabilities": {lab: 1.0 if lab == r.label else 0.0 for lab in LABELS}}}
    return {"id": r.id, "repo": r.repo, "state": state, "questions": ISSUE_TYPE_QUESTION, "gold": gold}


def eval_row(r):
    return {"id": r.id, "state": pp.preprocess(r.title, r.body), "questions": ISSUE_TYPE_QUESTION,
            "expected": {QUESTION_ID: r.label}, "tags": [f"repo:{r.repo}"]}


def to_json(row):
    return json.dumps(row, ensure_ascii=False)


def write_lines(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.writelines(line + "\n" for line in lines)


def review_sample(train):
    picks = sorted(random.Random(SEED).sample(train, REVIEW_N), key=lambda r: r.row)
    out = ["# Manual review sample (30 train rows, seed 42)", "",
           "Contains raw issue text. Gitignored; never commit. Bodies are cleaned by preprocess(),",
           f"first {REVIEW_BODY_CHARS} chars, indented 4 spaces.", ""]
    for r in picks:
        clean = pp.preprocess(r.title, r.body)["body"]
        out += [f"## {r.id}", "", f"- repo: {r.repo}", f"- label: {r.label}", f"- title: {r.title}",
                f"- body length raw -> cleaned: {len(r.body)} -> {len(clean)}", ""]
        out += ["    " + line for line in clean[:REVIEW_BODY_CHARS].split("\n")] + [""]
    return out


def step_hit_rates(records):
    """Share of bodies changed by each preprocess step, using preprocess's own step functions."""
    cfg = pp.PreprocessConfig()
    steps = [("CRLF/CR -> LF", pp.normalise_newlines),
             ("1 HTML comments", pp.strip_html_comments),
             ("2 code blocks collapsed", lambda t: pp.collapse_code_blocks(t, cfg.max_code_lines)),
             ("3a images", pp.replace_images),
             ("3b URLs", pp.replace_urls),
             ("4 whitespace", pp.normalise_whitespace),
             ("5 truncated at max_body_chars", lambda t: t[: cfg.max_body_chars])]
    hits = Counter()
    extra = Counter()
    for r in records:
        t = r.body
        for name, fn in steps:
            u = fn(t)
            hits[name] += u != t
            t = u
        if t != pp.preprocess(r.title, r.body)["body"]:
            raise BuildError(f"{r.id}: step chain differs from preprocess()")
        extra["any change"] += t != r.body
        extra["raw body empty or blank"] += r.body.strip() == ""
        extra["cleaned body empty"] += t == ""
        extra["cleaned body < 20 chars"] += len(t) < 20
    return [(name, hits[name]) for name, _ in steps] + list(extra.items())


def card_block(splits, records):
    out = [CARD_BEGIN, "", "### Split counts (repo x label)", ""]
    for name in SPLITS:
        c = Counter((r.repo, r.label) for r in splits[name])
        repos = sorted({r.repo for r in splits[name]})
        out += [f"**{name}** ({len(splits[name])} rows)", "",
                "| repo | " + " | ".join(LABELS) + " | total |", "|---|" + "---:|" * (len(LABELS) + 1)]
        for repo in repos:
            vals = [c[(repo, lab)] for lab in LABELS]
            out.append(f"| {repo} | " + " | ".join(map(str, vals)) + f" | {sum(vals)} |")
        tot = [sum(c[(repo, lab)] for repo in repos) for lab in LABELS]
        out += ["| **total** | " + " | ".join(map(str, tot)) + f" | {sum(tot)} |", ""]
    out += ["### Dropped official-train rows", "", "| id | content_sha1 | reason |", "|---|---|---|"]
    out += [f"| {r.id} | `{r.hash}` | {reason} |" for r, reason in splits["dropped"]]
    n = len(records)
    out += ["", f"### Preprocessing hit rates (all {n} raw issues, train + test)", "",
            "| step / property | bodies | share |", "|---|---:|---:|"]
    out += [f"| {name} | {k} | {k / n:.1%} |" for name, k in step_hit_rates(records)]
    return out + ["", CARD_END]


def update_card(card_path, block):
    text = card_path.read_text(encoding="utf-8")
    if text.count(CARD_BEGIN) != 1 or text.count(CARD_END) != 1:
        raise BuildError(f"{card_path}: needs exactly one generated-block marker pair")
    head, rest = text.split(CARD_BEGIN)
    _, tail = rest.split(CARD_END)
    card_path.write_text(head + "\n".join(block) + tail, encoding="utf-8")


def build(raw_dir, processed_dir, manifests_dir, sample_ids_path, card_path=None,
          expected_sha256=SHA256, real_data_checks=True):
    raw_dir, processed_dir, manifests_dir = Path(raw_dir), Path(processed_dir), Path(manifests_dir)
    for name, expected in expected_sha256.items():
        actual = sha256_file(raw_dir / name)
        if actual != expected:
            raise BuildError(f"{raw_dir / name}: sha256 {actual}, expected {expected}")
    train = to_records("train", load_raw(raw_dir / SOURCES["train"]))
    test = to_records("test", load_raw(raw_dir / SOURCES["test"]))
    sample_rows = {int(x) for x in Path(sample_ids_path).read_text().split()}
    unknown = sorted(row for row in sample_rows if not 0 <= row < len(train))
    if unknown:
        raise BuildError(f"sample rows outside official train: {unknown}")

    splits = make_splits(train, test, sample_rows)
    check_splits(splits, len(train), sample_rows)
    if real_data_checks:
        dropped_rows = {r.row for r, _ in splits["dropped"]}
        if (len(train), len(test), dropped_rows) != (REAL_TRAIN_ROWS, REAL_TEST_ROWS, REAL_DROPPED_ROWS):
            raise BuildError(f"real-data check failed: train {len(train)}, test {len(test)}, "
                             f"dropped rows {sorted(dropped_rows)}")

    write_lines(processed_dir / "train.jsonl", [to_json(train_row(r)) for r in splits["train"]])
    for name in ("val", "test"):
        write_lines(processed_dir / f"{name}.jsonl", [to_json(eval_row(r)) for r in splits[name]])
    for name in SPLITS:
        write_lines(manifests_dir / f"{name}.txt", [f"{r.id}\t{r.hash}" for r in splits[name]])
    write_lines(manifests_dir / "dropped_train.txt", [f"{r.id}\t{r.hash}\t{why}" for r, why in splits["dropped"]])
    write_lines(processed_dir / "review_sample_30.md", review_sample(splits["train"]))
    if card_path is not None:
        update_card(Path(card_path), card_block(splits, train + test))
    return splits


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--raw", type=Path, default=ROOT / "data" / "raw")
    parser.add_argument("--processed", type=Path, default=ROOT / "data" / "processed")
    parser.add_argument("--manifests", type=Path, default=ROOT / "data" / "manifests")
    parser.add_argument("--sample-ids", type=Path, default=ROOT / "results" / "phase0_sample_ids.txt")
    parser.add_argument("--card", type=Path, default=ROOT / "data" / "DATA_CARD.md")
    args = parser.parse_args(argv)
    splits = build(args.raw, args.processed, args.manifests, args.sample_ids, args.card)

    print("§8.7 checks passed: id and content-hash disjoint across train/val/test; "
          f"train {len(splits['train'])} + val {len(splits['val'])} + dropped {len(splits['dropped'])} "
          f"= {REAL_TRAIN_ROWS}; Phase 0 sample rows all in train; dropped rows = "
          f"{sorted(r.row for r, _ in splits['dropped'])}")
    print(f"{'split':6} {'repo':24} " + " ".join(f"{lab:>9}" for lab in LABELS) + f" {'total':>6}")
    for name in SPLITS:
        c = Counter((r.repo, r.label) for r in splits[name])
        for repo in sorted({r.repo for r in splits[name]}):
            vals = [c[(repo, lab)] for lab in LABELS]
            print(f"{name:6} {repo:24} " + " ".join(f"{v:>9}" for v in vals) + f" {sum(vals):>6}")
        print(f"{name:6} {'TOTAL':24} " + " ".join(f"{sum(c[(rp, lab)] for rp in {r.repo for r in splits[name]}):>9}"
                                                    for lab in LABELS) + f" {len(splits[name]):>6}")


if __name__ == "__main__":
    sys.exit(main())
